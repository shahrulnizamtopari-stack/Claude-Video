#!/usr/bin/env python3
"""Captions from the script + the voiceover transcript → assets/story.js.
The script's spelling is kept; each word takes the time of the transcript word with the same index
(the voice was read from this script, so the word counts match; the build stops if they don't).
*word* = key word (orange). Each string is one caption line group shown together."""
import json, os
ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
LINES = [
 "Benda kecik ni simpan *gas* yang boleh *meletup,*",
 "tapi kau selamba je simpan dalam *poket.*",
 "Macam mana dia boleh keluar *api* dengan satu *petik* je?",
 "Jom kita *bongkar.*",
 "Badan dia ni sebenarnya *tangki.*",
 "Dalam tu ada *butana,* gas yang *dimampat* kuat-kuat",
 "sampai jadi *cecair.*",
 "Sekarang kita *belah* dia.",
 "Kat atas ada *roda* besi.",
 "Bawah roda tu ada *batu* *api.*",
 "Dan *spring* ni tolak batu tu",
 "supaya sentiasa *rapat* dengan roda.",
 "Bila ibu jari kau pusing *roda,*",
 "dia *kikis* batu api tu,",
 "terus keluar *percikan* panas.",
 "Ibu jari yang sama tekan *tuas* ni,",
 "*injap* pun terbuka.",
 "Cecair butana tadi terus jadi *gas,*",
 "naik ikut *tiub,* keluar kat atas.",
 "Percikan jumpa gas, pap, *menyala!*",
 "Lepas je tuas, injap *tutup,* api *padam.*",
 "*Simple* kan?",
]
tr = json.load(open(os.path.join(ROOT, "assets", "transcript.json")))
n = sum(len(l.split()) for l in LINES)
assert n == len(tr), f"script has {n} words, transcript has {len(tr)}"
out, i = [], 0
for l in LINES:
    ws = []
    for raw in l.split():
        ws.append({"t": raw.strip("*"), "k": raw.startswith("*"), "at": round(tr[i]["start"], 3)}); end = tr[i]["end"]; i += 1
    out.append({"a": ws[0]["at"], "b": round(end, 3), "words": ws})
for a, b in zip(out, out[1:]): a["b"] = min(a["b"], b["a"])  # a line leaves when the next one starts
open(os.path.join(ROOT, "assets", "story.js"), "w").write("// generated by tools/build_story.py\nexport const LINES = " + json.dumps(out, ensure_ascii=False) + ";\n")
print(len(out), "lines,", n, "words, voice ends", tr[-1]["end"])

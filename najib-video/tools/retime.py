#!/usr/bin/env python3
"""Fit the film to the real voiceover.

1. Align the Whisper transcript (assets/transcript.raw.json) to the script by text (difflib), so misheard
   words ("Bangluh", "Amno", "K1 MDB") still get the right times and captions keep the script's spelling.
   Extra spoken words ("ringgit", "perpuluhan") are skipped.
2. Write assets/transcript.json (script words with real times) for build_captions.py.
3. Write assets/timing.js (window.WS: words per segment, window.SCENE: scene starts, window.END) used by the
   composition to put every animation on its word, and assets/timing.json for make_sfx.py.
4. Rewrite the clip windows (data-start / data-duration) in index.html to the new scene starts.
The voice is never stretched: the film takes the voice's length.
"""
import json, os, re, difflib, subprocess, sys
sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from build_captions import SEGMENTS
ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
A = lambda *p: os.path.join(ROOT, *p)

def norm(w):
    w = re.sub(r"[^a-z0-9]", "", w.lower())
    return re.sub(r"^rm(?=\d)", "", w)

raw = json.load(open(A("assets", "transcript.raw.json")))
raw = raw.get("words", raw) if isinstance(raw, dict) else raw
raw = [w for w in raw if norm(w["text"])]
script = [(si, w) for si, (_, _, txt) in enumerate(SEGMENTS) for w in txt.split()]
a, b = [norm(w) for _, w in script], [norm(w["text"]) for w in raw]
times = [None] * len(script)
for tag, i1, i2, j1, j2 in difflib.SequenceMatcher(a=a, b=b, autojunk=False).get_opcodes():
    if tag == "equal":
        for k in range(i2 - i1): times[i1 + k] = (raw[j1 + k]["start"], raw[j1 + k]["end"])
    elif tag in ("replace", "delete"):
        if j2 > j1: t0, t1 = raw[j1]["start"], raw[j2 - 1]["end"]
        else: t0 = t1 = raw[j1 - 1]["end"] if j1 > 0 else 0.0
        ch = [max(1, len(a[i])) for i in range(i1, i2)]; tot = sum(ch); acc = 0
        for k, i in enumerate(range(i1, i2)):
            times[i] = (t0 + (t1 - t0) * acc / tot, t0 + (t1 - t0) * (acc + ch[k]) / tot); acc += ch[k]
        print(f"{tag:7s}", [script[i][1] for i in range(i1, i2)], "<-", [raw[j]["text"] for j in range(j1, j2)])
assert all(times), [script[i][1] for i, t in enumerate(times) if t is None]

words = [{"text": w, "start": round(t[0], 3), "end": round(t[1], 3), "seg": si} for (si, w), t in zip(script, times)]
nseg = len(SEGMENTS)
first = [next(w for w in words if w["seg"] == s) for s in range(nseg)]
voice_end = float(subprocess.check_output(["ffprobe", "-v", "error", "-show_entries", "format=duration", "-of", "csv=p=0", A("assets", "voiceover.mp3")]))
END = round(max(words[-1]["end"], voice_end - 0.3) + 1.5, 2)          # hold the final question ~1.5 s
SCENE = [0.0] + [round(first[s]["start"] - 0.28, 2) for s in range(1, nseg)]
for s in range(nseg):
    e = SCENE[s + 1] if s + 1 < nseg else END
    print(f"scene {s+1:2d}: {SCENE[s]:6.2f} – {e:6.2f}  ({e - SCENE[s]:4.1f}s)  {SEGMENTS[s][2][:52]}")
print("END", END)

json.dump([{k: w[k] for k in ("text", "start", "end")} for w in words], open(A("assets", "transcript.json"), "w"), indent=0, ensure_ascii=False)
ws = [[{"t": w["text"], "s": w["start"], "e": w["end"]} for w in words if w["seg"] == s] for s in range(nseg)]
json.dump({"WS": ws, "SCENE": SCENE, "END": END}, open(A("assets", "timing.json"), "w"), ensure_ascii=False)
open(A("assets", "timing.js"), "w").write(
    "// generated by tools/retime.py from the voiceover; do not edit\n"
    f"window.WS = {json.dumps(ws, ensure_ascii=False)};\nwindow.SCENE = {json.dumps(SCENE)};\nwindow.END = {END};\n")

# clip windows: scene i shows from SCENE[i] until the next scene has faded over it
html = open(A("index.html")).read()
def setwin(el_id, start, dur):
    global html
    pat = re.compile(r'(id="' + re.escape(el_id) + r'"[^>]*?data-start=")[0-9.]+(" data-duration=")[0-9.]+(")')
    html, n = pat.subn(lambda m: f"{m.group(1)}{start:g}{m.group(2)}{dur:g}{m.group(3)}", html)
    assert n == 1, (el_id, n)
for s in range(nseg):
    e = SCENE[s + 1] + 0.45 if s + 1 < nseg else END
    setwin(f"s{s+1}", SCENE[s], round(e - SCENE[s], 2))
setwin("dive", 0, round(SCENE[1] + 0.45, 2))
for el in ("root", "bar", "captions-host", "mix"):
    if f'id="{el}"' in html: setwin(el, 0, END)
open(A("index.html"), "w").write(html)
print(len(words), "words aligned; index.html windows updated")

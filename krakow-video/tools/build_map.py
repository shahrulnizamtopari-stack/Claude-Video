#!/usr/bin/env python3
"""OSM (Overpass JSON) -> assets/map.json in local metres around the Main Square.
x = east, z = south (three.js: -z is north). Data © OpenStreetMap contributors, ODbL."""
import json, math, sys, os
ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
src = sys.argv[1]
d = json.load(open(src))["elements"]
cloth = next(e for e in d if e.get("tags", {}).get("name") == "Sukiennice")
lat0 = sum(p["lat"] for p in cloth["geometry"]) / len(cloth["geometry"]); lon0 = sum(p["lon"] for p in cloth["geometry"]) / len(cloth["geometry"])
ringpts = [p for e in d if e.get("tags", {}).get("name") == "Rynek Główny" and "highway" in e["tags"] for p in e["geometry"]]
K = math.cos(math.radians(lat0))
P = lambda la, lo: [round((lo - lon0) * 111320 * K, 1), round(-(la - lat0) * 110540, 1)]
R = 900  # keep everything within this radius
out = {"center": [lat0, lon0], "buildings": [], "roads": [], "parks": [], "landmarks": {}}
LM = {"Sukiennice": "cloth", "Bazylika Mariacka": "mary", "Kościół Mariacki": "mary", "Wieża Ratuszowa": "tower", "Wieża ratuszowa": "tower"}
for e in d:
    t = e.get("tags", {}); g = e.get("geometry")
    if not g: continue
    pts = [P(p["lat"], p["lon"]) for p in g]
    if min(math.hypot(*p) for p in pts) > R: continue
    if "building" in t and len(pts) >= 4:
        h = None
        try: h = float(str(t.get("height", "")).replace("m", "").strip())
        except ValueError: pass
        if h is None and "building:levels" in t:
            try: h = float(t["building:levels"]) * 3.4 + 2
            except ValueError: pass
        if h is None: h = 13 + (abs(hash(e["id"])) % 7)
        lm = LM.get(t.get("name", ""))
        if lm == "mary": h = max(h, 26)
        if lm == "cloth": h = max(h, 14)
        if lm == "tower": h = max(h, 58)
        b = {"p": pts[:-1] if pts[0] == pts[-1] else pts, "h": round(min(h, 70), 1)}
        if lm: b["lm"] = lm; out["landmarks"][lm] = [round(sum(p[0] for p in b["p"]) / len(b["p"]), 1), round(sum(p[1] for p in b["p"]) / len(b["p"]), 1)]
        out["buildings"].append(b)
    elif "highway" in t and t["highway"] not in ("steps", "corridor", "platform", "elevator"):
        w = {"primary": 3, "secondary": 3, "tertiary": 2.4, "residential": 1.8, "living_street": 1.8, "pedestrian": 1.8, "service": 1.2}.get(t["highway"], 0.8)
        out["roads"].append({"p": pts, "w": w})
    elif t.get("leisure") == "park" or t.get("landuse") == "grass":
        out["parks"].append(pts)
# Rynek corners (square is rotated ~45°)
rg = [P(p["lat"], p["lon"]) for p in ringpts]
# the square is a diamond on screen: N corner = Sławkowska, E = by St Mary's / Sienna, S = Grodzka
E = min(rg, key=lambda p: p[1] - p[0]); W = max(rg, key=lambda p: p[1] - p[0]); S = max(rg, key=lambda p: p[0] + p[1]); N = min(rg, key=lambda p: p[0] + p[1])
out["landmarks"]["mary"] = P(50.06165, 19.93905)
out["square"] = {"N": N, "E": E, "S": S, "W": W}
def way_pts(name):
    s = []
    for e in d:
        if e.get("tags", {}).get("name") == name and "highway" in e["tags"] and e.get("geometry"):
            s += [P(p["lat"], p["lon"]) for p in e["geometry"]]
    return s
sl = [p for p in way_pts("Sławkowska") if p[1] < N[1] and math.hypot(p[0] - N[0], p[1] - N[1]) < 260]
gr = sorted({tuple(p) for p in way_pts("Grodzka")}, key=lambda p: p[1])
st = sorted({tuple(p) for p in way_pts("Stradomska")}, key=lambda p: p[1])
entry = min(sl, key=lambda p: p[1]) if sl else [N[0] + 60, N[1] - 220]
route = [entry, N, E, S] + [list(p) for p in gr if p[1] > S[1] + 5] + [list(p) for p in st]
END = route[-1]
# drop near-duplicates
clean = []
for p in route:
    if not clean or math.hypot(p[0] - clean[-1][0], p[1] - clean[-1][1]) > 4: clean.append(p)
out["route"] = clean
out["stops"] = {"N": N, "E": E, "S": S, "end": END}
json.dump(out, open(os.path.join(ROOT, "assets", "map.json"), "w"), separators=(",", ":"))
L = sum(math.hypot(clean[i + 1][0] - clean[i][0], clean[i + 1][1] - clean[i][1]) for i in range(len(clean) - 1))
print(len(out["buildings"]), "buildings,", len(out["roads"]), "roads,", len(out["parks"]), "parks; route", round(L), "m,", len(clean), "pts; landmarks", out["landmarks"], "square", out["square"], "end", END)
open(os.path.join(ROOT, "assets", "map.js"), "w").write("// generated by tools/build_map.py from OpenStreetMap (© OpenStreetMap contributors, ODbL)\nexport default " + json.dumps(out, separators=(",", ":")) + ";\n")

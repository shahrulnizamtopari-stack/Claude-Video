#!/usr/bin/env python3
"""Natural Earth (public domain) -> assets/geo.js. Usage: make_geo.py <admin1.geojson> <countries50.geojson>
MY: Malaysian states (lon/lat rings, simplified). NB: neighbour land near Malaysia. WORLD: coarse land rings for the globe."""
import json, sys, os
ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
def dp(pts, eps):
    if len(pts) < 3: return pts
    a, b = pts[0], pts[-1]; dx, dy = b[0]-a[0], b[1]-a[1]; L = (dx*dx+dy*dy) ** 0.5 or 1e-9
    i, dm = 0, 0
    for k in range(1, len(pts)-1):
        p = pts[k]; d = abs(dy*(p[0]-a[0]) - dx*(p[1]-a[1])) / L if (dx or dy) else ((p[0]-a[0])**2+(p[1]-a[1])**2)**.5
        if d > dm: i, dm = k, d
    if dm > eps: return dp(pts[:i+1], eps)[:-1] + dp(pts[i:], eps)
    return [a, b]
def area(r): return abs(sum(r[i][0]*r[i-1][1]-r[i-1][0]*r[i][1] for i in range(len(r)))) / 2
def rings(geom, eps, minA):
    polys = geom["coordinates"] if geom["type"] == "MultiPolygon" else [geom["coordinates"]]
    out = []
    for p in polys:
        r = p[0]
        if area(r) < minA: continue
        s = dp([[round(x, 3), round(y, 3)] for x, y in r], eps)
        if len(s) >= 4: out.append(s[:-1])
    return out
a1 = json.load(open(sys.argv[1])); c50 = json.load(open(sys.argv[2]))
MY = {}
for f in a1["features"]:
    if f["properties"].get("adm0_a3") != "MYS": continue
    n = f["properties"]["name"]
    if n in ("Putrajaya",): continue
    MY[n] = rings(f["geometry"], 0.008, 0.0015 if n not in ("Labuan", "Kuala Lumpur", "Perlis", "Pulau Pinang", "Melaka") else 0.0002)
def clip_ok(r, box): return any(box[0] <= x <= box[2] and box[1] <= y <= box[3] for x, y in r)
NB, WORLD = {}, []
BOX = (94, -8, 122, 14)
for f in c50["features"]:
    iso = f["properties"]["ADM0_A3"]
    if iso != "MYS":
        rs = [r for r in rings(f["geometry"], 0.02, 0.01) if clip_ok(r, BOX)]
        if rs: NB[iso] = rs
    WORLD += rings(f["geometry"], 0.25, 0.3)
js = "// generated by tools/make_geo.py from Natural Earth (public domain)\n"
js += "export const MY = " + json.dumps(MY, separators=(",", ":")) + ";\n"
js += "export const NB = " + json.dumps(NB, separators=(",", ":")) + ";\n"
js += "export const WORLD = " + json.dumps(WORLD, separators=(",", ":")) + ";\n"
open(os.path.join(ROOT, "assets", "geo.js"), "w").write(js)
print({k: sum(len(r) for r in v) for k, v in MY.items()}, list(NB), len(WORLD), len(js)//1024, "KB")

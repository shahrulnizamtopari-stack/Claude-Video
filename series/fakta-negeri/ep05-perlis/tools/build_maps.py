#!/usr/bin/env python3
"""After tools/bake_all.sh: writes assets/maps/shapes.js (projected borders/points/lines per shot) and dive-last.jpg."""
import json, os, subprocess
ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__))); M = os.path.join(ROOT, "assets", "maps")
SH = {}
for name, f in [("dive", "dive-shapes.json"), ("coast", "coast-shapes.json"), ("outro", "outro-shapes.json")]:
    SH[name] = json.load(open(os.path.join(M, f)))
    if name in ("coast",):  # only points/lines needed there
        SH[name]["polys"] = []
open(os.path.join(M, "shapes.js"), "w").write("// generated by tools/build_maps.py\nexport const SH = " + json.dumps(SH, separators=(",", ":")) + ";\n")
print("shapes.js", os.path.getsize(os.path.join(M, "shapes.js")) // 1024, "KB")
